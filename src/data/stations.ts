/**
 * Filter stations by search term and city
 */
export function filterStations(
  stations: Station[],
  options: {
    query?: string;
    city?: string;
    filter?: string;
  }
): Station[] {
  const { query = '', city = 'All', filter = 'All' } = options;
  const q = query.trim().toLowerCase();

  return stations.filter((station) => {
    // City filter
    if (city && city !== 'All' && city !== 'All Cities') {
      if (station.city.toLowerCase() !== city.toLowerCase()) {
        return false;
      }
    }

    // Query filter
    if (q) {
      const matchName = station.name.toLowerCase().includes(q);
      const matchCity = station.city.toLowerCase().includes(q);
      const matchAddress = station.address.toLowerCase().includes(q);
      const matchConnector = station.connectors.some((c) => c.toLowerCase().includes(q));
      if (!matchName && !matchCity && !matchAddress && !matchConnector) {
        return false;
      }
    }

    // Tag filter
    if (filter === 'Ultra-Fast 350kW' && station.powerKw < 350) return false;
    if (filter === 'DC Fast 180kW' && (station.powerKw < 180 || station.powerKw >= 350)) return false;
    if (filter === 'Available Now' && (station.status !== 'Available' || station.availablePlugs <= 0)) return false;
    if (filter === '24/7 Open' && !station.open247) return false;
    if (filter === 'CCS2' && !station.connectors.includes('CCS2')) return false;
    if (filter === 'Type 2' && !station.connectors.includes('Type 2')) return false;

    return true;
  });
}
